import assert from 'node:assert/strict';
import {createDemoAccount, DEMO_UID} from '../src/demoData';
import {setDemoSession, requireLiveSession} from '../src/demoSession';
const data=createDemoAccount(new Date('2026-10-19T10:00:00+08:00'));
assert.ok(data.reports.length && data.schedules.length && data.fleet.length && data.records.length);
assert.ok(data.records.every(item=>item.ownerUid===DEMO_UID && item.source==='demo'));
for(const booking of data.bookings) assert.ok(data.records.some(item=>item.id===booking.recyclingSubmissionId));
assert.equal(data.bookings[0].pickupDate,'2026-10-20');
assert.notEqual(createDemoAccount().records, data.records);
setDemoSession(true); assert.throws(requireLiveSession,/sample data only/);
setDemoSession(false); assert.doesNotThrow(requireLiveSession);
console.log('PASS: populated demo fixtures, booking links, date, isolation and write protection.');
import {getDeviceAccounts, saveDeviceAccount} from '../src/appData';
const browserHistory=new Map<string,string>();
Object.defineProperty(globalThis,'localStorage',{configurable:true,value:{getItem:(k:string)=>browserHistory.get(k)??null,setItem:(k:string,v:string)=>browserHistory.set(k,v),removeItem:(k:string)=>browserHistory.delete(k)}});
const resident={id:'real-resident',email:'resident@example.invalid',name:'Resident',avatar:'R',bg:'',zone:'',area:'',phone:'',collectionDays:''};
browserHistory.set('bingo_device_accounts',JSON.stringify([resident,{...resident,id:'admin-history',email:'Admin123@bingo.com'}]));
assert.deepEqual(getDeviceAccounts().map(a=>a.email),[resident.email]);
assert.equal(JSON.parse(browserHistory.get('bingo_device_accounts')!).length,1);
saveDeviceAccount({...resident,email:'admin123@bingo.com'});
assert.equal(getDeviceAccounts().length,1);
console.log('PASS: resident account history removes only reserved admin entries and blocks re-saving them.');
